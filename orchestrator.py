class Stage1SignatureWorker(threading.Thread):
    """
    Stage 1 Worker:
      Pulls flows from raw_flow_queue.
      Evaluates with SignatureEngine:
        - Match: Converts to UnifiedAlert and enqueues to alert_ingress_queue.
        - Unmatched (Clean): Passed automatically by SignatureEngine to stage2_queue!
    """

    def __init__(
        self,
        signature_engine: SignatureEngine,
        raw_flow_queue: queue.Queue[Dict[str, Any]],
        alert_ingress_queue: queue.Queue[UnifiedAlert],
        shutdown_event: threading.Event,
    ):
        super().__init__(name="Stage1SignatureWorker", daemon=True)
        self.signature_engine = signature_engine
        self.raw_flow_queue = raw_flow_queue
        self.alert_ingress_queue = alert_ingress_queue
        self.shutdown_event = shutdown_event
        self.processed_count = 0

    def run(self):
        logger.info("Stage1SignatureWorker started.")
        while not self.shutdown_event.is_set():
            try:
                flow = self.raw_flow_queue.get(timeout=0.1)
            except queue.Empty:
                continue

            try:
                alert, matched = self.signature_engine.evaluate(flow)
                self.processed_count += 1

                if matched and alert:
                    u_alert = UnifiedAlert(
                        alert_id=alert.alert_id,
                        stage="STAGE_1_SIGNATURE",
                        severity=alert.severity.value,
                        category=alert.category,
                        rule_or_model=alert.rule_name,
                        description=alert.description,
                        source_ip=str(flow.get("src_ip", "")),
                        source_port=int(flow.get("src_port", 0)),
                        dest_ip=str(flow.get("dst_ip", "")),
                        dest_port=int(flow.get("dst_port", 0)),
                        protocol=str(flow.get("protocol", "")),
                        flow_metrics={
                            k: flow.get(k)
                            for k in [
                                "packet_count", "byte_count", "flow_duration",
                                "bytes_per_sec", "packets_per_sec",
                                "syn_flag_ratio", "tcp_rst_ratio",
                            ]
                        },
                        detection_details={"matched_detail": alert.matched_detail},
                        timestamp=alert.timestamp,
                    )
                    self.alert_ingress_queue.put_nowait(u_alert)
            except Exception as e:
                logger.error("Error in Stage 1 evaluation: %s", e)
            finally:
                self.raw_flow_queue.task_done()

        logger.info("Stage1SignatureWorker terminated cleanly.")


class Stage2AnomalyWorker(threading.Thread):
    """
    Stage 2 Worker:
      Pulls clean flows from stage2_queue (unmatched by Stage 1).
      Evaluates with NetworkAnomalyDetector (Isolation Forest + Diurnal Z-scores):
        - Anomaly: Converts to UnifiedAlert and enqueues to alert_ingress_queue.
        - Normal: Clean baseline traffic.
    """

    def __init__(
        self,
        anomaly_detector: NetworkAnomalyDetector,
        stage2_queue: queue.Queue[Dict[str, Any]],
        alert_ingress_queue: queue.Queue[UnifiedAlert],
        shutdown_event: threading.Event,
    ):
        super().__init__(name="Stage2AnomalyWorker", daemon=True)
        self.anomaly_detector = anomaly_detector
        self.stage2_queue = stage2_queue
        self.alert_ingress_queue = alert_ingress_queue
        self.shutdown_event = shutdown_event
        self.processed_count = 0
        self.anomalies_detected = 0

    def run(self):
        logger.info("Stage2AnomalyWorker started.")
        while not self.shutdown_event.is_set():
            try:
                flow = self.stage2_queue.get(timeout=0.1)
            except queue.Empty:
                continue

            try:
                result: AnomalyResult = self.anomaly_detector.predict_flow(flow)
                self.processed_count += 1

                if result.is_anomaly:
                    self.anomalies_detected += 1
                    ts = flow.get("timestamp", flow.get("window_end", time.time()))
                    u_alert = UnifiedAlert(
                        alert_id=f"ALT-ML-{int(ts * 1000)}",
                        stage="STAGE_2_ANOMALY",
                        severity=result.severity,
                        category="Behavioral Anomaly",
                        rule_or_model="IsolationForestDiurnal",
                        description="Flow volume/behavior deviated significantly from historical diurnal baseline",
                        source_ip=str(flow.get("src_ip", "")),
                        source_port=int(flow.get("src_port", 0)),
                        dest_ip=str(flow.get("dst_ip", "")),
                        dest_port=int(flow.get("dst_port", 0)),
                        protocol=str(flow.get("protocol", "")),
                        flow_metrics={
                            k: flow.get(k)
                            for k in [
                                "packet_count", "byte_count", "flow_duration",
                                "bytes_per_sec", "packets_per_sec",
                                "syn_flag_ratio", "tcp_rst_ratio",
                            ]
                        },
                        detection_details={
                            "anomaly_score": result.anomaly_score,
                            "raw_decision_score": result.raw_decision_score,
                            "hour_of_day": result.hour_of_day,
                            "zscore_bytes_per_sec": result.zscores.get("zscore_bytes_per_sec", 0.0),
                            "zscore_packets_per_sec": result.zscores.get("zscore_packets_per_sec", 0.0),
                        },
                        timestamp=float(ts),
                    )
                    self.alert_ingress_queue.put_nowait(u_alert)
            except Exception as e:
                logger.error("Error in Stage 2 evaluation: %s", e)
            finally:
                self.stage2_queue.task_done()

        logger.info("Stage2AnomalyWorker terminated cleanly.")


class AlertAggregatorWorker(threading.Thread):
    """
    Alert Ingress & Deduplication Worker:
      Pulls alerts from alert_ingress_queue.
      Processes through AlertAggregator (30-second window by Source IP).
      Periodically flushes expired deduplication windows.
    """

    def __init__(
        self,
        aggregator: AlertAggregator,
        alert_ingress_queue: queue.Queue[UnifiedAlert],
        shutdown_event: threading.Event,
    ):
        super().__init__(name="AlertAggregatorWorker", daemon=True)
        self.aggregator = aggregator
        self.alert_ingress_queue = alert_ingress_queue
        self.shutdown_event = shutdown_event
        self.last_flush_check = time.time()

    def run(self):
        logger.info("AlertAggregatorWorker started.")
        while not self.shutdown_event.is_set():
            try:
                alert = self.alert_ingress_queue.get(timeout=0.1)
                self.aggregator.process_alert(alert)
                self.alert_ingress_queue.task_done()
            except queue.Empty:
                pass

            now = time.time()
            if (now - self.last_flush_check) >= 1.0:
                self.aggregator.check_expired_windows(now)
                self.last_flush_check = now

        # Flush remaining alerts on shutdown
        while not self.alert_ingress_queue.empty():
            try:
                alert = self.alert_ingress_queue.get_nowait()
                self.aggregator.process_alert(alert)
                self.alert_ingress_queue.task_done()
            except queue.Empty:
                break

        self.aggregator.close()
        logger.info("AlertAggregatorWorker terminated cleanly.")


