@dataclass
class DedupState:
    """Tracks alert aggregation state for a specific Source IP."""
    source_ip: str
    first_seen: float
    last_seen: float
    alert_count: int
    highest_severity: str
    initial_alert: UnifiedAlert
    stages: Set[str] = field(default_factory=set)
    rules_triggered: Set[str] = field(default_factory=set)


class AlertAggregator:
    """
    Aggregates and deduplicates alerts by Source IP across a 30-second window.

    Rules:
      1. First alert for a Source IP: Logged immediately to the JSON stream.
      2. Subsequent alerts within 30s: Suppressed from spamming; counter incremented.
      3. Severity Escalation: If a subsequent alert has higher severity than previous,
         an immediate escalation notice is logged.
      4. Window Expiration: When 30s elapses since the first alert, if multiple alerts
         occurred, an AGGREGATED_SUMMARY JSON record is emitted and state is cleared.
    """

    SEVERITY_ORDER = {"LOW": 1, "MEDIUM": 2, "HIGH": 3, "CRITICAL": 4}

    def __init__(
        self,
        dedup_window_seconds: float = 30.0,
        output_file: Optional[str] = None,
        console_stream: bool = True,
        output_io: Optional[TextIO] = None,
    ):
        self.dedup_window_seconds = float(dedup_window_seconds)
        self.output_file = output_file
        self.console_stream = console_stream
        self.output_io = output_io

        self._active_windows: Dict[str, DedupState] = {}
        self._lock = threading.Lock()

        self._file_handle: Optional[TextIO] = None
        if self.output_file:
            self._file_handle = open(self.output_file, mode="a", encoding="utf-8")

        # Telemetry counters
        self.total_alerts_received = 0
        self.total_alerts_emitted = 0
        self.total_alerts_suppressed = 0
        self.total_summaries_emitted = 0

    def process_alert(self, alert: UnifiedAlert) -> bool:
        """
        Processes an incoming alert.
        Returns True if alert was emitted immediately, False if suppressed.
        """
        now = alert.timestamp
        src_ip = alert.source_ip
        emitted = False

        with self._lock:
            self.total_alerts_received += 1
            state = self._active_windows.get(src_ip)

            # Check if an active window exists and is still within 30s
            if state is not None and (now - state.first_seen) < self.dedup_window_seconds:
                # Existing active window: suppress duplicate
                state.alert_count += 1
                state.last_seen = now
                state.stages.add(alert.stage)
                state.rules_triggered.add(alert.rule_or_model)
                self.total_alerts_suppressed += 1

                # Check severity escalation
                current_prio = self.SEVERITY_ORDER.get(alert.severity, 1)
                highest_prio = self.SEVERITY_ORDER.get(state.highest_severity, 1)

                if current_prio > highest_prio:
                    state.highest_severity = alert.severity
                    # Emit escalation alert
                    escalation_record = {
                        "timestamp": datetime.fromtimestamp(now, tz=timezone.utc).isoformat(),
                        "event_type": "SEVERITY_ESCALATION",
                        "source_ip": src_ip,
                        "previous_severity": state.initial_alert.severity,
                        "escalated_severity": alert.severity,
                        "triggering_alert_id": alert.alert_id,
                        "stage": alert.stage,
                        "rule_or_model": alert.rule_or_model,
                        "description": alert.description,
                    }
                    self._emit_json(escalation_record)
                    self.total_alerts_emitted += 1
                    emitted = True

            else:
                # Window expired or first alert for this Source IP
                if state is not None:
                    # Flush previous window summary before starting new window
                    self._flush_state(state, now)

                # Initialize new 30-second window
                new_state = DedupState(
                    source_ip=src_ip,
                    first_seen=now,
                    last_seen=now,
                    alert_count=1,
                    highest_severity=alert.severity,
                    initial_alert=alert,
                    stages={alert.stage},
                    rules_triggered={alert.rule_or_model},
                )
                self._active_windows[src_ip] = new_state

                # Emit initial alert immediately
                alert_dict = alert.to_dict()
                alert_dict["dedup_metadata"] = {
                    "is_first_in_window": True,
                    "window_duration_sec": self.dedup_window_seconds,
                    "window_expires_at": datetime.fromtimestamp(
                        now + self.dedup_window_seconds, tz=timezone.utc
                    ).isoformat(),
                }
                self._emit_json(alert_dict)
                self.total_alerts_emitted += 1
                emitted = True

        return emitted

    def check_expired_windows(self, current_time: Optional[float] = None) -> int:
        """
        Periodically checks and flushes expired 30-second deduplication windows.
        Emits AGGREGATED_SUMMARY events for IPs that had suppressed alerts.
        """
        now = current_time if current_time is not None else time.time()
        flushed_count = 0

        with self._lock:
            expired_ips = [
                ip for ip, state in self._active_windows.items()
                if (now - state.first_seen) >= self.dedup_window_seconds
            ]
            for ip in expired_ips:
                state = self._active_windows.pop(ip)
                if self._flush_state(state, now):
                    flushed_count += 1

        return flushed_count

    def _flush_state(self, state: DedupState, now: float) -> bool:
        """Emits summary record if multiple alerts were suppressed."""
        if state.alert_count > 1:
            summary = {
                "timestamp": datetime.fromtimestamp(now, tz=timezone.utc).isoformat(),
                "event_type": "AGGREGATED_SUMMARY",
                "source_ip": state.source_ip,
                "window_duration_sec": self.dedup_window_seconds,
                "first_seen": datetime.fromtimestamp(state.first_seen, tz=timezone.utc).isoformat(),
                "last_seen": datetime.fromtimestamp(state.last_seen, tz=timezone.utc).isoformat(),
                "total_alerts_in_window": state.alert_count,
                "total_alerts_suppressed": state.alert_count - 1,
                "highest_severity": state.highest_severity,
                "stages_involved": list(state.stages),
                "rules_or_models_triggered": list(state.rules_triggered),
                "message": (
                    f"Source IP {state.source_ip} generated {state.alert_count} total alerts "
                    f"within the 30-second window ({state.alert_count - 1} duplicates suppressed)."
                ),
            }
            self._emit_json(summary)
            self.total_summaries_emitted += 1
            return True
        return False

    def _emit_json(self, record: Dict[str, Any]):
        """Outputs a structured JSON line to terminal and/or file."""
        json_str = json.dumps(record)

        if self.console_stream:
            print(json_str, flush=True)

        if self.output_io:
            self.output_io.write(json_str + "\n")
            self.output_io.flush()

        if self._file_handle:
            self._file_handle.write(json_str + "\n")
            self._file_handle.flush()

    def close(self):
        """Flushes all pending windows and closes open files."""
        with self._lock:
            now = time.time()
            for ip, state in list(self._active_windows.items()):
                self._flush_state(state, now)
            self._active_windows.clear()

        if self._file_handle:
            self._file_handle.close()
            self._file_handle = None


