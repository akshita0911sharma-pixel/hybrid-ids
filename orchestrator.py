class HybridIDSOrchestrator:
    """
    Central Orchestrator integrating:
      1. Live / Synthetic Flow Capture
      2. Stage 1 Signature Engine
      3. Stage 2 ML Anomaly Detector
      4. Alert Aggregator & 30-Second Source IP Deduplication
    """

    def __init__(
        self,
        interface: Optional[str] = None,
        bpf_filter: Optional[str] = None,
        model_path: Optional[str] = None,
        alert_log_file: Optional[str] = "alerts.jsonl",
        dedup_window_seconds: float = 30.0,
        console_json_stream: bool = True,
    ):
        self.interface = interface
        self.bpf_filter = bpf_filter
        self.model_path = model_path
        self.alert_log_file = alert_log_file
        self.dedup_window_seconds = dedup_window_seconds
        self.console_json_stream = console_json_stream

        self.shutdown_event = threading.Event()

        # Inter-stage queues
        self.raw_flow_queue: queue.Queue[Dict[str, Any]] = queue.Queue(maxsize=50000)
        self.stage2_queue: queue.Queue[Dict[str, Any]] = queue.Queue(maxsize=50000)
        self.alert_ingress_queue: queue.Queue[UnifiedAlert] = queue.Queue(maxsize=20000)

        # Core engines
        self.signature_engine: Optional[SignatureEngine] = None
        self.anomaly_detector: Optional[NetworkAnomalyDetector] = None
        self.alert_aggregator: Optional[AlertAggregator] = None

        # Capture worker / monitor
        self.flow_monitor: Optional[FlowMonitor] = None

        # Worker threads
        self.stage1_worker: Optional[Stage1SignatureWorker] = None
        self.stage2_worker: Optional[Stage2AnomalyWorker] = None
        self.aggregator_worker: Optional[AlertAggregatorWorker] = None

    def initialize_engines(self):
        """Initializes Signature Engine, ML Anomaly Detector, and Alert Aggregator."""
        logger.info("Initializing Stage 1 Signature Engine...")
        self.signature_engine = SignatureEngine(
            secondary_queue=self.stage2_queue,
            alerts_queue=queue.Queue(maxsize=10000),
            enable_stateful_scan_detection=True,
        )

        logger.info("Initializing Stage 2 ML Anomaly Engine...")
        if self.model_path and os.path.exists(self.model_path):
            logger.info("Loading pretrained AnomalyDetector model from '%s'", self.model_path)
            self.anomaly_detector = NetworkAnomalyDetector.load_model(self.model_path)
        else:
            logger.info("No pretrained model specified. Auto-training baseline on diurnal dataset...")
            synthetic_train_df = generate_synthetic_diurnal_dataset(num_days=7, samples_per_hour=30)
            self.anomaly_detector = NetworkAnomalyDetector(n_estimators=100, contamination=0.02)
            self.anomaly_detector.fit(synthetic_train_df)
            if self.model_path:
                self.anomaly_detector.save_model(self.model_path)

        logger.info("Initializing Alert Aggregator (30s Source IP dedup window)...")
        self.alert_aggregator = AlertAggregator(
            dedup_window_seconds=self.dedup_window_seconds,
            output_file=self.alert_log_file,
            console_stream=self.console_json_stream,
        )

    def start(self):
        """Starts all pipeline worker threads and sniffer."""
        self.initialize_engines()

        logger.info("Starting pipeline worker threads...")
        self.stage1_worker = Stage1SignatureWorker(
            signature_engine=self.signature_engine,
            raw_flow_queue=self.raw_flow_queue,
            alert_ingress_queue=self.alert_ingress_queue,
            shutdown_event=self.shutdown_event,
        )

        self.stage2_worker = Stage2AnomalyWorker(
            anomaly_detector=self.anomaly_detector,
            stage2_queue=self.stage2_queue,
            alert_ingress_queue=self.alert_ingress_queue,
            shutdown_event=self.shutdown_event,
        )

        self.aggregator_worker = AlertAggregatorWorker(
            aggregator=self.alert_aggregator,
            alert_ingress_queue=self.alert_ingress_queue,
            shutdown_event=self.shutdown_event,
        )

        self.aggregator_worker.start()
        self.stage2_worker.start()
        self.stage1_worker.start()

        # Connect FlowAggregator metrics export to raw_flow_queue
        def _on_flow_metrics_batch(metrics_list: List[FlowMetrics]):
            for m in metrics_list:
                try:
                    self.raw_flow_queue.put_nowait(m.to_dict())
                except queue.Full:
                    logger.warning("raw_flow_queue full! Dropped flow record.")

        # If an interface is specified, start live Scapy capture
        if self.interface is not None:
            logger.info("Starting live flow capture on interface '%s'...", self.interface)
            self.flow_monitor = FlowMonitor(
                interface=self.interface,
                bpf_filter=self.bpf_filter,
                exporter=FlowExporter(console_output=False),
            )
            # Override monitor's aggregator callback to pipe into raw_flow_queue
            self.flow_monitor.aggregator_worker = SlidingWindowAggregator(
                packet_queue=self.flow_monitor.packet_queue,
                shutdown_event=self.flow_monitor.shutdown_event,
                window_size=5.0,
                slide_interval=1.0,
                metrics_callback=_on_flow_metrics_batch,
            )
            self.flow_monitor.start()

        # Register OS signal handlers for clean SIGINT / SIGTERM shutdown
        def _sig_handler(sig, frame):
            logger.info("Received signal %s. Stopping orchestrator gracefully...", sig)
            self.stop()

        try:
            signal.signal(signal.SIGINT, _sig_handler)
            signal.signal(signal.SIGTERM, _sig_handler)
        except (ValueError, AttributeError):
            pass

    def stop(self):
        """Stops all workers and flushes pending queues."""
        if self.shutdown_event.is_set():
            return
        logger.info("Signaling all orchestrator components to stop...")
        self.shutdown_event.set()

        if self.flow_monitor:
            self.flow_monitor.stop()

        if self.stage1_worker and self.stage1_worker.is_alive():
            self.stage1_worker.join(timeout=3.0)

        if self.stage2_worker and self.stage2_worker.is_alive():
            self.stage2_worker.join(timeout=3.0)

        if self.aggregator_worker and self.aggregator_worker.is_alive():
            self.aggregator_worker.join(timeout=3.0)

        logger.info("HybridIDSOrchestrator stopped successfully.")

    def enqueue_flow(self, flow_dict: Dict[str, Any]):
        """Directly injects a flow dictionary into the raw_flow_queue."""
        self.raw_flow_queue.put(flow_dict)


