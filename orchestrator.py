@dataclass
class UnifiedAlert:
    """
    Standardized alert structure generated by either Stage 1 or Stage 2.
    """
    alert_id: str
    stage: str  # "STAGE_1_SIGNATURE" or "STAGE_2_ANOMALY"
    severity: str  # "LOW", "MEDIUM", "HIGH", "CRITICAL"
    category: str
    rule_or_model: str
    description: str
    source_ip: str
    source_port: int
    dest_ip: str
    dest_port: int
    protocol: str
    flow_metrics: Dict[str, Any]
    detection_details: Dict[str, Any]
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        iso_time = datetime.fromtimestamp(self.timestamp, tz=timezone.utc).isoformat()
        return {
            "timestamp": iso_time,
            "event_type": "ALERT",
            "alert_id": self.alert_id,
            "stage": self.stage,
            "severity": self.severity,
            "category": self.category,
            "rule_or_model": self.rule_or_model,
            "description": self.description,
            "source_ip": self.source_ip,
            "source_port": self.source_port,
            "dest_ip": self.dest_ip,
            "dest_port": self.dest_port,
            "protocol": self.protocol,
            "flow_metrics": self.flow_metrics,
            "detection_details": self.detection_details,
        }

    def to_json(self) -> str:
        return json.dumps(self.to_dict())


